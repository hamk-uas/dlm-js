%% Multivariate DLM: two sensors observing the same local‑level+trend state
% Model:
%   y(t) = F·x(t) + v, v ~ N(0, diag(V1², V2²))
%   x(t) = G·x(t-1) + w, w ~ N(0, W)
%
% F = [1 0; 1 0]  — both sensors observe the level component only
% G = [1 1; 0 1]  — local linear trend (order=1)
%
% This exercises p=2 with order=1. Both sensors share the same underlying
% state but have different observation noise levels.

disp('Multivariate DLM test: p=2, order=1');

n = 100;

% Deterministic "truth" — simple linear trend + sinusoid
t = (1:n)';
true_level = 50 + 0.3 * t;
true_signal = true_level + 5 * sin(2 * pi * t / 25);

% Deterministic "noise" for reproducibility (no random numbers)
noise1 = 3 * sin(t * 0.73) + 2 * cos(t * 1.17);
noise2 = 5 * sin(t * 0.41) + 4 * cos(t * 0.89);

y1 = true_signal + noise1;   % sensor 1 (lower noise)
y2 = true_signal + noise2;   % sensor 2 (higher noise)

% Stack as n×p matrix (MATLAB DLM convention: y is n rows × p cols)
y = [y1, y2];

% System matrices
p_obs = 2;
m = 2;  % state dim: level + slope

% F: [p, m] — both sensors observe just the level
F = [1, 0; 1, 0];

% V: observation std devs, n×p
s1 = 4;
s2 = 7;
V = repmat([s1, s2], n, 1);  % [n, p]

% G: order=1 local linear trend
G = [1 1; 0 1];

% W: process noise covariance
w = [3, 1];
W = diag(w.^2);

% Initial state
x0 = [mean(y1(1:12)); 0];
c0_val = (abs(x0(1)) * 0.5)^2;
C0 = c0_val * eye(m);

%% Pass 1: diffuse prior (matching dlm-js two-pass procedure)
out1 = dlmsmo(y, F, V, x0, G, W, C0, [], 0, 1, 1);

% Refine initial state from smoothed estimates (matching dlm-js Pass 2)
x0_refined = out1.x(:,1);
C0_refined = out1.C(:,:,1) * 100;

%% Pass 2: refined initial state
out = dlmsmo(y, F, V, x0_refined, G, W, C0_refined, [], 0, 1, 1);

%% Save inputs
inputs = struct( ...
  'y', y, ...       % [n, p]
  'F', F, ...       % [p, m]
  'V', V, ...       % [n, p] obs noise std devs
  's', [s1, s2], ...% [p] scalar obs noise std devs
  'w', w, ...       % process noise std devs
  'G', G, ...       % [m, m]
  'W', W, ...       % [m, m]
  'x0', x0, ...     % [m, 1]
  'C0', C0, ...     % [m, m]
  'x0_refined', x0_refined, ...  % [m, 1]
  'C0_refined', C0_refined, ...  % [m, m]
  'n', n, ...
  'p', p_obs, ...
  'm', m ...
);
save_json(inputs, 'tests/multivariate-in.json');

%% Save outputs
% Smoothed states: x is [m, n] in MATLAB DLM → transpose to [n, m]
% Covariance: C is [m, m, n] → keep as-is (test code handles it)
result = struct( ...
  'x', out.x, ...          % [m, n] smoothed states
  'C', out.C, ...          % [m, m, n] smoothed covariances
  'xf', out.xf, ...        % [m, n] filtered states
  'Cf', out.Cf, ...        % [m, m, n] filtered covariances
  'v', out.v, ...          % [p, n] innovations
  'Cp', out.Cp, ...        % [p, p, n] innovation covariances
  'yhat', out.yhat, ...    % [n, p] filter predictions
  'ystd', out.ystd, ...    % [n, p] prediction std devs
  'resid0', out.resid0, ...% [n, p] raw residuals (y - yhat)
  'resid', out.resid, ...  % [n, p] scaled residuals
  'lik', out.lik, ...      %  -2·logL (scalar)
  's2', out.s2, ...        % residual variance
  'nobs', out.nobs, ...    % [p] number of valid obs per series
  'n', n, ...
  'p', p_obs, ...
  'm', m ...
);
save_json(result, 'tests/multivariate-out-m.json');
disp('  done');

