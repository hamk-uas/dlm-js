%% Test p=2 with order=1 + AR(2) (trend + autoregression, m=4)
disp('Multivariate DLM test: p=2, order=1, AR(2)');

% Generate system matrices for order=1 + AR(2)
options_ar2 = struct('order', 1, 'arphi', [0.6, -0.3]);
[G_ar2, F_ar2_row] = dlmgensys(options_ar2);
m_ar2 = size(G_ar2, 1);  % should be 4

% F for p=2: both sensors observe level (state 0) and AR component (state 2)
% F_ar2_row = [1, 0, 1, 0] from dlmgensys
F_ar2 = [F_ar2_row; F_ar2_row];  % [2, 4]

% Noise parameters
s1_ar2 = 3;
s2_ar2 = 6;
V_ar2 = repmat([s1_ar2, s2_ar2], n, 1);  % [n, 2]

% Process noise std devs: [level, slope, ar1_state, ar2_state]
w_ar2 = [0.5, 0.05, 2, 0];
W_ar2 = diag(w_ar2.^2);

% Generate deterministic data (trend + AR oscillation + deterministic noise)
ar2_state = zeros(n, 1);
ar2_state(1) = 3;
ar2_state(2) = -1;
for ti = 3:n
  ar2_state(ti) = 0.6 * ar2_state(ti-1) + (-0.3) * ar2_state(ti-2) + 0.5 * sin(ti * 0.37);
end
true_signal_ar2 = true_level + ar2_state;

noise1_ar2 = 3 * sin(t * 0.53) + 2 * cos(t * 1.07);
noise2_ar2 = 6 * sin(t * 0.31) + 4 * cos(t * 0.79);
y1_ar2 = true_signal_ar2 + noise1_ar2;
y2_ar2 = true_signal_ar2 + noise2_ar2;
y_ar2 = [y1_ar2, y2_ar2];

% Initial state
x0_ar2 = [mean(y1_ar2(1:12)); 0; 0; 0];
c0_ar2 = (abs(x0_ar2(1)) * 0.5)^2;
C0_ar2 = c0_ar2 * eye(m_ar2);

% Pass 1: diffuse prior
out1_ar2 = dlmsmo(y_ar2, F_ar2, V_ar2, x0_ar2, G_ar2, W_ar2, C0_ar2, [], 0, 1, 1);

% Pass 2: refined initial state
x0_ar2r = out1_ar2.x(:,1);
C0_ar2r = out1_ar2.C(:,:,1) * 100;
out_ar2 = dlmsmo(y_ar2, F_ar2, V_ar2, x0_ar2r, G_ar2, W_ar2, C0_ar2r, [], 0, 1, 1);

inputs_ar2mv = struct( ...
  'y', y_ar2, ...
  'F', F_ar2, ...
  'V', V_ar2, ...
  's', [s1_ar2, s2_ar2], ...
  'w', w_ar2, ...
  'G', G_ar2, ...
  'W', W_ar2, ...
  'x0', x0_ar2, ...
  'C0', C0_ar2, ...
  'x0_refined', x0_ar2r, ...
  'C0_refined', C0_ar2r, ...
  'n', n, ...
  'p', p_obs, ...
  'm', m_ar2, ...
  'arCoefficients', [0.6, -0.3] ...
);
save_json(inputs_ar2mv, 'tests/multivariate-ar2-in.json');

result_ar2mv = struct( ...
  'x', out_ar2.x, ...
  'C', out_ar2.C, ...
  'xf', out_ar2.xf, ...
  'Cf', out_ar2.Cf, ...
